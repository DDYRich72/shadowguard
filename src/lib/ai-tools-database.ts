// Build a lookup map for fast matching
const ALIAS_MAP = new Map<string, AIToolEntry>();
for (const tool of AI_TOOLS_DATABASE) {
  for (const alias of tool.aliases) {
    ALIAS_MAP.set(alias.toLowerCase(), tool);
  }
}

/**
 * Check if a Google Workspace app name matches a known AI tool
 */
export function matchAITool(appName: string): AIToolEntry | null {
  const normalizedName = appName.toLowerCase().trim();

  // Direct alias match
  const directMatch = ALIAS_MAP.get(normalizedName);
  if (directMatch) return directMatch;

  // Partial match — check if any alias is contained in the app name
  for (const [alias, tool] of ALIAS_MAP) {
    if (normalizedName.includes(alias) || alias.includes(normalizedName)) {
      return tool;
    }
  }

  // Keyword-based detection for unknown AI tools
  const aiKeywords = [
    "ai", "gpt", "llm", "machine learning", "neural", "deep learning",
    "natural language", "nlp", "generative", "copilot", "assistant",
    "chatbot", "text generator", "image generator", "code generator",
  ];

  const hasAIKeyword = aiKeywords.some((kw) => normalizedName.includes(kw));
  if (hasAIKeyword) {
    return {
      name: appName,
      aliases: [normalizedName],
      category: "Unknown AI Tool",
      data_access_scope: "medium",
      has_soc2: false,
      has_gdpr: false,
      has_hipaa: false,
      data_residency: "unknown",
      risk_base_score: 70, // Unknown tools get higher base risk
    };
  }

  return null;
}

