  "  if (skewSeconds > 300) return res.status(401).json({ error: \"stale_event\" });",
  "  if (!timingSafeHexEqual(sign(req.body), signature)) {",
  "    return res.status(401).json({ error: \"bad_signature\" });",
  "  }",
  "",
  "  if (acceptedEventIds.has(eventId)) return res.json({ ok: true, duplicate: true });",
