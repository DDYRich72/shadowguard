const NEXTJS_RECEIVER_EXAMPLE = [
  'import { createHmac, timingSafeEqual } from "node:crypto";',
  "",
  "const SIGNING_SECRET = process.env.AGENTGUARD_EXPORT_SIGNING_SECRET ?? \"\";",
  "const TOLERANCE_SECONDS = 300;",
  "const acceptedEventIds = new Set<string>(); // Replace with durable storage.",
  "",
  "function canonicalJson(value: unknown): string {",
  "  if (value === null || typeof value !== \"object\") return JSON.stringify(value);",
  "  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(\",\")}]`;",
  "  return `{${Object.entries(value as Record<string, unknown>)",
  "    .filter(([, nested]) => nested !== undefined)",
  "    .sort(([left], [right]) => left.localeCompare(right))",
  "    .map(([key, nested]) => `${JSON.stringify(key)}:${canonicalJson(nested)}`)",
  "    .join(\",\")}}`;",
  "}",
  "",
  "function sign(payload: unknown): string {",
  "  // HMAC-SHA256 over ShadowGuard canonical JSON.",
  "  return createHmac(\"sha256\", SIGNING_SECRET)",
  "    .update(canonicalJson(payload), \"utf8\")",
  "    .digest(\"hex\");",
  "}",
  "",
  "function timingSafeHexEqual(leftHex: string, rightHex: string): boolean {",
  "  const left = Buffer.from(leftHex, \"hex\");",
  "  const right = Buffer.from(rightHex, \"hex\");",
  "  return left.length === right.length && timingSafeEqual(left, right);",
  "}",
  "",
  "export async function POST(request: Request) {",
  "  const eventId = request.headers.get(\"x-shadowguard-event-id\");",
  "  const timestamp = Number(request.headers.get(\"x-shadowguard-timestamp\"));",
  "  const signature = request.headers.get(\"x-shadowguard-signature\");",
  "  if (!eventId || !Number.isFinite(timestamp) || !signature) {",
  "    return Response.json({ error: \"missing_signature_headers\" }, { status: 401 });",
  "  }",
  "",
  "  const skewSeconds = Math.abs(Math.floor(Date.now() / 1000) - timestamp);",
  "  if (skewSeconds > TOLERANCE_SECONDS) {",
  "    return Response.json({ error: \"stale_event\" }, { status: 401 });",
  "  }",
  "",
  "  const payload = await request.json();",
  "  if (!timingSafeHexEqual(sign(payload), signature)) {",
  "    return Response.json({ error: \"bad_signature\" }, { status: 401 });",
  "  }",
  "",
  "  if (acceptedEventIds.has(eventId)) {",
  "    return Response.json({ ok: true, duplicate: true });",
  "  }",
  "",
  "  acceptedEventIds.add(eventId);",
  "  // Persist metadata such as payload.activity.riskLevel, dataClassification,",
  "  // source, and contentLength. AgentGuard exports do not include raw prompts.",
  "  return Response.json({ ok: true });",
  "}",
].join("\n");

