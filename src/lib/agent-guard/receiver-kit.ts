  "  return `{${Object.entries(value)",
  "    .filter(([, nested]) => nested !== undefined)",
  "    .sort(([left], [right]) => left.localeCompare(right))",
  "    .map(([key, nested]) => `${JSON.stringify(key)}:${canonicalJson(nested)}`)",
  "    .join(\",\")}}`;",
  "}",
  "",
  "function sign(payload) {",
  "  // HMAC-SHA256 over ShadowGuard canonical JSON.",
  "  return createHmac(\"sha256\", SIGNING_SECRET)",
  "    .update(canonicalJson(payload), \"utf8\")",
  "    .digest(\"hex\");",
  "}",
  "",
  "function timingSafeHexEqual(leftHex, rightHex) {",
  "  const left = Buffer.from(leftHex, \"hex\");",
  "  const right = Buffer.from(rightHex, \"hex\");",
  "  return left.length === right.length && timingSafeEqual(left, right);",
  "}",
  "",
  "app.post(\"/agentguard/events\", (req, res) => {",
  "  const eventId = req.header(\"x-shadowguard-event-id\");",
  "  const timestamp = Number(req.header(\"x-shadowguard-timestamp\"));",
  "  const signature = req.header(\"x-shadowguard-signature\");",
